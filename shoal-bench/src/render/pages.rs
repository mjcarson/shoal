//! The set of pages the results are rendered onto, and what every one of them has in common
//!
//! # Why there is more than one page
//!
//! There used to be one. It reached 13,617 lines and 1.1 MB, of which ninety percent was
//! eighty-eight near-identical charts drawn one per workload identifier in alphabetical order. A
//! reader looking for what an insert costs found it at line 8,559, after forty-eight arms of an
//! encryption sweep. Nothing on it said how to read any of it, and two of its nine sections
//! consisted of a sentence saying the current capture had no data.
//!
//! The split is by **question**, not by workload: what a mixture costs, what width costs, what kind
//! of table costs what, what a skewed key space does, what the wire costs, what fan-out costs. Each
//! page opens with its families' four blocks - what it measures, how to read it, what would make it
//! wrong, what it cannot say - before it draws anything.
//!
//! # The set is fixed
//!
//! [`PAGES`] is a constant, not something derived from the captures. Every page needs an entry in
//! `docs/src/SUMMARY.md`, and `create-missing = false` in `book.toml` means a `SUMMARY` entry with
//! no file behind it fails the whole book build. A page that appeared because somebody added a
//! workload would break the book on the commit that added it.
//!
//! Which is also why **every page renders even when it has nothing to draw**. A capture that
//! measured no encryption still has to produce `transport.md`, saying so.

