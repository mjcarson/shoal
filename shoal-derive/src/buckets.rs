//! Generate what a bucket declared in a schema brings with it
//!
//! A field `posters: Bucket<Posters>` generates two rows, `PostersObjectMeta` and
//! `PostersStripeMeta`, as ordinary persistent unsorted tables of the schema; an enum of the
//! schema's buckets; and the marker's [`BucketRows`] impl naming the two
//! ([S2](../../../docs/src/object-storage/buckets.md#what-the-macro-generates),
//! [F79](../../../docs/src/features/bucket-schema.md)). All of it is emitted in both halves, since
//! a client's query and response enums have a variant for every table, generated ones included.
//!
//! The rows' fields are of types `shoal::shared::objects` defines once, so the layout is the same
//! in every schema, and is folded into the fingerprint as a whole through
//! `OBJECT_ROWS_LAYOUT`.
//!
//! # Invariants
//!
//! **Everything generated here names `::shoal::shared` paths and nothing else**, so a client half
//! with a bucket links no engine. The one exception is the derives the rows carry, which name
//! `::shoal::rkyv` and `::shoal::ShoalUnsortedTable`, both client safe.
//!
//! **A generated row's name comes from its marker alone**, so reordering a schema's fields moves no
//! table's identity.
//!
//! [`BucketRows`]: ../../shoal_proto/shared/objects/trait.BucketRows.html

use quote::{format_ident, quote};

use crate::schema::{Bucket, Schema};

/// Extend a token stream with everything the schema's buckets generate
///
/// # Arguments
///
/// * `stream` - The stream to extend
/// * `schema` - The schema whose buckets to generate for
pub fn add(stream: &mut proc_macro2::TokenStream, schema: &Schema) {
    // the rows and the marker's impl, for each bucket in turn
    for bucket in &schema.buckets {
        add_rows(stream, schema, bucket);
    }
    // and the enum naming every bucket, which every schema has
    add_enum(stream, schema);
}

/// Extend a token stream with one bucket's two rows and its marker's `BucketRows` impl
///
/// # Arguments
///
/// * `stream` - The stream to extend
/// * `schema` - The schema declaring the bucket
/// * `bucket` - The bucket to generate for
fn add_rows(stream: &mut proc_macro2::TokenStream, schema: &Schema, bucket: &Bucket) {
    // the names everything below spells
    let db = &schema.db;
    let db_name = db.to_string();
    let client = format_ident!("{}Client", db);
    let marker = &bucket.marker;
    let marker_name = marker.to_string();
    let objects = &bucket.objects;
    let stripes = &bucket.stripes;
    // the generated row's own query types, and the schema's wire enums, which ObjectQueries builds
    let objects_get = format_ident!("{}Get", objects);
    let objects_delete = format_ident!("{}Delete", objects);
    let objects_filter = format_ident!("{}Filter", objects);
    let stripes_get = format_ident!("{}Get", stripes);
    let stripes_filter = format_ident!("{}Filter", stripes);
    let query_kinds = format_ident!("{}QueryKinds", db);
    let archived_response = format_ident!("Archived{}ResponseKinds", db);
    // the docs each row carries, naming the bucket it belongs to
    let objects_doc = format!(
        "The object metadata of bucket {marker_name}: one entry for each object at a path whose \
         hash is this row's key. Generated by `#[shoal::db]`; no client's query reaches it."
    );
    let stripes_doc = format!(
        "The stripe metadata of bucket {marker_name}: one row for each stripe written in place. \
         Generated by `#[shoal::db]`; no client's query reaches it."
    );
    stream.extend(quote! {
        #[doc = #objects_doc]
        #[derive(
            Debug,
            Clone,
            PartialEq,
            ::shoal::rkyv::Archive,
            ::shoal::rkyv::Serialize,
            ::shoal::rkyv::Deserialize,
            ::shoal::ShoalUnsortedTable,
        )]
        #[rkyv(crate = ::shoal::rkyv, derive(Debug))]
        #[shoal_table(db = #db_name)]
        pub struct #objects {
            /// The hash of the paths whose entries this row holds, `objects::path_key`
            #[shoal(partition)]
            pub key: u64,
            /// Moved by every committed change to this row, and what a change is conditional on
            #[shoal(filter, update)]
            pub version: u64,
            /// One entry for each path that hashes to this key, nearly always one
            #[shoal(update)]
            pub entries: ::std::vec::Vec<::shoal::shared::objects::ObjectEntry>,
        }

        #[automatically_derived]
        impl ::shoal::deepsize2::DeepSizeOf for #objects {
            /// The heap this row holds, which is its entries'
            ///
            /// # Arguments
            ///
            /// * `context` - What has already been counted
            fn deep_size_of_children(&self, context: &mut ::shoal::deepsize2::Context) -> usize {
                // the key and the version are inline, so the entries are all the heap there is
                self.entries.deep_size_of_children(context)
            }
        }

        #[doc = #stripes_doc]
        #[derive(
            Debug,
            Clone,
            PartialEq,
            ::shoal::rkyv::Archive,
            ::shoal::rkyv::Serialize,
            ::shoal::rkyv::Deserialize,
            ::shoal::ShoalUnsortedTable,
        )]
        #[rkyv(crate = ::shoal::rkyv, derive(Debug))]
        #[shoal_table(db = #db_name)]
        pub struct #stripes {
            /// The consumer whose stripe this is, minted when its binding was committed
            #[shoal(partition)]
            pub consumer: u64,
            /// The object the stripe is part of, never reused
            #[shoal(partition)]
            pub object: u128,
            /// Which stripe of the object this is
            #[shoal(partition)]
            pub stripe: u64,
            /// How many writes to this stripe have committed, and what a commit is conditional on
            #[shoal(filter, update)]
            pub sequence: u64,
            /// The label each stripe chunk must carry, by position
            #[shoal(update)]
            pub labels: ::std::vec::Vec<::shoal::shared::objects::Label>,
            /// How much of the stripe holds bytes
            #[shoal(update)]
            pub length: u64,
            /// The object's truncate epoch when this row was last committed
            #[shoal(update)]
            pub stamp: u64,
            /// The least truncate epoch a writer must have read to commit: a truncate cutting
            /// inside this stripe fences it first
            #[shoal(update)]
            pub fence: u64,
            /// Whether reclamation has reclaimed this stripe; a reclaimed row is never deleted
            #[shoal(update)]
            pub tombstone: bool,
            /// The bytes of small writes that rode in their commits, until enough holders fold them
            ///
            /// Boxed, so a row with none pending - nearly every row - archives a pointer's width
            /// for it rather than the whole of an empty one
            #[shoal(update)]
            pub pending: ::std::option::Option<
                ::std::boxed::Box<::shoal::shared::objects::PendingBytes>
            >,
        }

        #[automatically_derived]
        impl ::shoal::deepsize2::DeepSizeOf for #stripes {
            /// The heap this row holds, which is its labels' and its pending bytes'
            ///
            /// # Arguments
            ///
            /// * `context` - What has already been counted
            fn deep_size_of_children(&self, context: &mut ::shoal::deepsize2::Context) -> usize {
                // every scalar is inline, so the labels and the pending bytes are the heap
                self.labels.deep_size_of_children(context)
                    + self.pending.deep_size_of_children(context)
            }
        }

        #[automatically_derived]
        impl ::shoal::shared::objects::BucketRows for #marker {
            /// The bucket's name, which is its marker's
            const NAME: &'static str = #marker_name;

            /// The client of the schema that declares this bucket
            type Client = #client;

            /// The row of the bucket's object metadata table
            type ObjectMeta = #objects;

            /// The row of the bucket's stripe metadata table
            type StripeMeta = #stripes;
        }

        #[automatically_derived]
        impl ::shoal::shared::objects::ObjectQueries for #marker {
            /// A get of the object metadata row under a key
            ///
            /// # Arguments
            ///
            /// * `key` - The row's key, a path's `path_key`
            fn get(key: u64) -> #query_kinds {
                // the key is the row's partition value, hashed as any get's is
                #objects_get::new(::std::vec![key]).into()
            }

            /// An insert of a row where none is stored
            ///
            /// # Arguments
            ///
            /// * `row` - The row
            fn create(row: ::shoal::shared::objects::ObjectRow) -> #query_kinds {
                use ::shoal::shared::queries::ConditionalInsert;
                // the generated row, inserted only where no row is
                #objects {
                    key: row.key,
                    version: row.version,
                    entries: row.entries,
                }
                .if_absent()
                .into()
            }

            /// An insert of a row over the one stored, if that one is still at `version`
            ///
            /// # Arguments
            ///
            /// * `row` - The row
            /// * `version` - The version of the row its writer read
            fn replace(row: ::shoal::shared::objects::ObjectRow, version: u64) -> #query_kinds {
                use ::shoal::shared::queries::ConditionalWrite;
                // the whole row, replacing only the version its writer read
                #objects {
                    key: row.key,
                    version: row.version,
                    entries: row.entries,
                }
                .if_matches(#objects_filter {
                    version: ::std::option::Option::Some(::std::vec![version]),
                })
                .into()
            }

            /// A delete of the row under a key, if it is still at `version`
            ///
            /// # Arguments
            ///
            /// * `key` - The row's key
            /// * `version` - The version of the row its writer read
            fn remove(key: u64, version: u64) -> #query_kinds {
                use ::shoal::shared::queries::ConditionalWrite;
                // the row's delete, only at the version its writer read
                #objects_delete::new(key)
                    .if_matches(#objects_filter {
                        version: ::std::option::Option::Some(::std::vec![version]),
                    })
                    .into()
            }

            /// Read what one of these queries came back as
            ///
            /// # Arguments
            ///
            /// * `response` - The archived answer
            fn answer(response: &#archived_response) -> ::shoal::shared::objects::MetaAnswer {
                // an answer of this bucket's object table, read into rows apart from the schema
                match response {
                    #archived_response::#objects(response) => {
                        ::shoal::shared::objects::meta_answer::<#objects>(response, |row| {
                            ::shoal::shared::objects::ObjectRow {
                                key: row.key.to_native(),
                                version: row.version.to_native(),
                                entries: ::shoal::shared::objects::owned_entries(&row.entries),
                            }
                        })
                    }
                    _ => ::shoal::shared::objects::MetaAnswer::Unexpected(
                        "an answer of another table",
                    ),
                }
            }

            /// Validate an answer's bytes and read what it came back as
            ///
            /// # Arguments
            ///
            /// * `raw` - The answer's archived bytes
            fn answer_bytes(raw: &[u8]) -> ::shoal::shared::objects::MetaAnswer {
                // aligned for the archive, then validated before anything is read
                ::shoal::shared::objects::with_aligned(raw, |raw| {
                    match ::shoal::rkyv::access::<#archived_response, ::shoal::rkyv::rancor::Error>(raw) {
                        ::std::result::Result::Ok(archived) => {
                            <Self as ::shoal::shared::objects::ObjectQueries>::answer(archived)
                        }
                        ::std::result::Result::Err(_) => ::shoal::shared::objects::MetaAnswer::Unexpected(
                            "an answer whose bytes do not validate",
                        ),
                    }
                })
            }

            /// The hash an object metadata row's key is placed by
            ///
            /// # Arguments
            ///
            /// * `key` - The row's key
            fn route_key(key: u64) -> u64 {
                <#objects as ::shoal::shared::traits::PartitionKeySupport>::get_partition_key_from_values(&key)
            }

            /// A get of the stripe metadata rows of some stripes, one key each
            ///
            /// # Arguments
            ///
            /// * `keys` - Each stripe's consumer, object and index
            fn stripe_get(keys: ::std::vec::Vec<(u64, u128, u64)>) -> #query_kinds {
                // the keys are the row's three partition values, hashed as any get's are
                #stripes_get::new(keys).into()
            }

            /// An insert of a stripe's row where none is stored
            ///
            /// # Arguments
            ///
            /// * `row` - The row
            fn stripe_create(row: ::shoal::shared::stripes::StripeRow) -> #query_kinds {
                use ::shoal::shared::queries::ConditionalInsert;
                // the generated row, inserted only where no row is
                #stripes {
                    consumer: row.consumer,
                    object: row.object,
                    stripe: row.stripe,
                    sequence: row.sequence,
                    labels: row.labels,
                    length: row.length,
                    stamp: row.stamp,
                    fence: row.fence,
                    tombstone: row.tombstone,
                    pending: row.pending,
                }
                .if_absent()
                .into()
            }

            /// An insert of a stripe's row over the one stored, if that one is still at `sequence`
            ///
            /// # Arguments
            ///
            /// * `row` - The row
            /// * `sequence` - The sequence of the row its writer read
            fn stripe_commit(row: ::shoal::shared::stripes::StripeRow, sequence: u64) -> #query_kinds {
                use ::shoal::shared::queries::ConditionalWrite;
                // the whole next row, replacing only the sequence its writer read
                #stripes {
                    consumer: row.consumer,
                    object: row.object,
                    stripe: row.stripe,
                    sequence: row.sequence,
                    labels: row.labels,
                    length: row.length,
                    stamp: row.stamp,
                    fence: row.fence,
                    tombstone: row.tombstone,
                    pending: row.pending,
                }
                .if_matches(#stripes_filter {
                    sequence: ::std::option::Option::Some(::std::vec![sequence]),
                })
                .into()
            }

            /// Validate a stripe metadata answer's bytes and read what it came back as
            ///
            /// # Arguments
            ///
            /// * `raw` - The answer's archived bytes
            fn stripe_answer_bytes(raw: &[u8]) -> ::shoal::shared::objects::StripeAnswer {
                // aligned for the archive, then validated before anything is read
                ::shoal::shared::objects::with_aligned(raw, |raw| {
                    match ::shoal::rkyv::access::<#archived_response, ::shoal::rkyv::rancor::Error>(raw) {
                        ::std::result::Result::Ok(#archived_response::#stripes(response)) => {
                            ::shoal::shared::objects::stripe_answer::<#stripes>(response, |row| {
                                let (labels, pending) =
                                    ::shoal::shared::objects::owned_stripe_parts(&row.labels, &row.pending);
                                ::shoal::shared::stripes::StripeRow {
                                    consumer: row.consumer.to_native(),
                                    object: row.object.to_native(),
                                    stripe: row.stripe.to_native(),
                                    sequence: row.sequence.to_native(),
                                    labels,
                                    length: row.length.to_native(),
                                    stamp: row.stamp.to_native(),
                                    fence: row.fence.to_native(),
                                    tombstone: row.tombstone,
                                    pending,
                                }
                            })
                        }
                        ::std::result::Result::Ok(_) => ::shoal::shared::objects::StripeAnswer::Unexpected(
                            "an answer of another table",
                        ),
                        ::std::result::Result::Err(_) => ::shoal::shared::objects::StripeAnswer::Unexpected(
                            "an answer whose bytes do not validate",
                        ),
                    }
                })
            }
        }
    });
}

/// Extend a token stream with the enum naming every bucket a schema declares
///
/// A schema that declares none still gets one, uninhabited, so that `QuerySupport::BucketNames`
/// always names a type.
///
/// # Arguments
///
/// * `stream` - The stream to extend
/// * `schema` - The schema whose buckets to name
fn add_enum(stream: &mut proc_macro2::TokenStream, schema: &Schema) {
    // the enum's name, beside the table enum's
    let enum_ident = format_ident!("{}Buckets", schema.db);
    // one variant a bucket, named after its marker
    let variants: Vec<_> = schema
        .buckets
        .iter()
        .map(|bucket| bucket.marker.clone())
        .collect();
    let names: Vec<String> = variants.iter().map(ToString::to_string).collect();
    let positions: Vec<usize> = (0..variants.len()).collect();
    // an uninhabited enum matches on nothing, and an inhabited one on every variant
    let (id_body, position_body, name_body) = if variants.is_empty() {
        (
            quote!(match *self {}),
            quote!(match *self {}),
            quote!(match *self {}),
        )
    } else {
        (
            quote! {
                match self {
                    #(#enum_ident::#variants => ::shoal::shared::identity::BucketId::of(#names),)*
                }
            },
            quote! {
                match self {
                    #(#enum_ident::#variants => #positions,)*
                }
            },
            quote! {
                match self {
                    #(#enum_ident::#variants => #names,)*
                }
            },
        )
    };
    stream.extend(quote! {
        /// The buckets this database declares, one variant a bucket
        #[derive(Debug, Clone, Copy, PartialEq, Eq, Hash, PartialOrd, Ord)]
        pub enum #enum_ident {
            #(
                #[doc = "A bucket this database declares"]
                #variants,
            )*
        }

        #[automatically_derived]
        impl ::shoal::shared::traits::BucketNameSupport for #enum_ident {
            /// Get the stable identity of this bucket, the hash of its name
            fn bucket_id(&self) -> ::shoal::shared::identity::BucketId {
                #id_body
            }

            /// Get where this bucket sits among the schema's buckets, in declaration order
            fn position(&self) -> usize {
                #position_body
            }

            /// Get this bucket's name, which is its marker's
            fn name(&self) -> &'static str {
                #name_body
            }
        }

        #[automatically_derived]
        impl std::fmt::Display for #enum_ident {
            /// Write the bucket's name
            ///
            /// # Arguments
            ///
            /// * `f` - The formatter to write too
            fn fmt(&self, f: &mut std::fmt::Formatter<'_>) -> std::fmt::Result {
                f.write_str(::shoal::shared::traits::BucketNameSupport::name(self))
            }
        }
    });
}
